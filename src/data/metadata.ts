const genreBySlug = new Map<string, string[]>()
for (const [genre, slugs] of Object.entries(GROUPS)) {
  for (const slug of slugs) {
    const current = genreBySlug.get(slug) ?? []
    if (!current.includes(genre)) current.push(genre)
    genreBySlug.set(slug, current)
  }
}

export function genresFor(slug: string) {
  return genreBySlug.get(slug) ?? ['Drama']
}
